use crate::dsl::{Part, ScorerLang, Value};
use crate::mocking::code::{Item, Judge, Module, arg_name};
use std::fmt::Write;

const JUDGE_USE_COT: bool = true;

pub(super) fn code(lang: ScorerLang, project: &str, items: &[Item], module: &Module, implementation: &str) -> String {
    let names = module.functions.join(", ");
    let body = match lang {
        ScorerLang::Python => {
            let name = implementation.trim_end_matches(".py");
            format!("if __package__:\n    from .{name} import {names}\nelse:\n    from {name} import {names}\n")
        }
        ScorerLang::Typescript => {
            let name = implementation.trim_end_matches(".ts");
            format!("import {{{names}}} from \"./{name}.js\";\n")
        }
    };
    let mut out = match lang {
        ScorerLang::Python => format!(
            "# generated by bts; edits will be overwritten\nimport braintrust\nfrom pydantic import BaseModel\nfrom typing import Any\n\nproject = braintrust.projects.create(name={})\n{body}",
            quoted(project)
        ),
        ScorerLang::Typescript => format!(
            "// generated by bts; edits will be overwritten\nimport braintrust from \"braintrust\";\nimport {{ z }} from \"zod/v3\";\n\nconst project = braintrust.projects.create({{ name: {} }});\n{body}",
            quoted(project)
        ),
    };
    for (item, function) in items.iter().zip(&module.functions) {
        match lang {
            ScorerLang::Python => {
                let params = format!("{function}_params");
                write!(
                    out,
                    "\n\nclass {params}(BaseModel):\n    input: Any = None\n    output: Any\n    expected: Any = None\n    metadata: Any = None\n\n\nproject.scorers.create(\n    name={},\n    slug={},\n    parameters={params},\n    handler={function},\n)\n",
                    quoted(item.name), quoted(item.slug),
                ).unwrap();
            }
            ScorerLang::Typescript => {
                write!(
                    out,
                    "\nproject.scorers.create({{\n  name: {},\n  slug: {},\n  parameters: z.object({{ input: z.any(), output: z.union([z.null(), z.boolean(), z.number(), z.string(), z.array(z.any()), z.record(z.any())]), expected: z.any(), metadata: z.any() }}),\n  handler: {function},\n}});\n",
                    quoted(item.name), quoted(item.slug),
                ).unwrap();
            }
        }
    }
    out
}

pub(super) fn judge(
    lang: ScorerLang,
    project: &str,
    name: &str,
    slug: &str,
    model: &str,
    prompt: &Value,
    options: Vec<(&str, f64)>,
) -> String {
    let prompt = mustache(prompt);
    let scores = options
        .iter()
        .map(|(label, score)| format!("{}: {score}", quoted(label)))
        .collect::<Vec<_>>()
        .join(", ");
    match lang {
        ScorerLang::Python => format!(
            "# generated by bts; edits will be overwritten\nimport braintrust\n\nproject = braintrust.projects.create(name={})\n\nproject.scorers.create(\n    name={},\n    slug={},\n    messages=[{{\"role\": \"user\", \"content\": {}}}],\n    model={},\n    use_cot={},\n    choice_scores={{{scores}}},\n)\n",
            quoted(project),
            quoted(name),
            quoted(slug),
            quoted(&prompt),
            quoted(model),
            if JUDGE_USE_COT { "True" } else { "False" },
        ),
        ScorerLang::Typescript => format!(
            "// generated by bts; edits will be overwritten\nimport braintrust from \"braintrust\";\n\nconst project = braintrust.projects.create({{ name: {} }});\n\nproject.scorers.create({{\n  name: {},\n  slug: {},\n  messages: [{{ role: \"user\", content: {} }}],\n  model: {},\n  useCot: {},\n  choiceScores: {{{scores}}},\n}});\n",
            quoted(project),
            quoted(name),
            quoted(slug),
            quoted(&prompt),
            quoted(model),
            JUDGE_USE_COT,
        ),
    }
}

pub(super) fn local_judge(judge: &Judge<'_>, function: &str) -> String {
    let prompt = mustache(judge.prompt);
    let scores = judge
        .options
        .iter()
        .map(|option| (option.label.clone(), option.score))
        .collect::<std::collections::BTreeMap<_, _>>();
    let scores = serde_json::to_string(&scores).expect("validated judge scores");
    match judge.lang {
        ScorerLang::Python => format!(
            "# generated by bts; edits will be overwritten.\nfrom autoevals import LLMClassifier\n\n{function} = LLMClassifier(\n    name={},\n    prompt_template={},\n    model={},\n    choice_scores={scores},\n    use_cot=True,\n)\n",
            quoted(judge.name),
            quoted(&prompt),
            quoted(judge.model),
        ),
        ScorerLang::Typescript => format!(
            "// generated by bts; edits will be overwritten.\nimport {{LLMClassifierFromTemplate}} from \"autoevals\";\n\nexport const {function} = LLMClassifierFromTemplate<any>({{\n    name: {},\n    promptTemplate: {},\n    model: {},\n    choiceScores: {scores},\n    useCoT: true,\n}});\n",
            quoted(judge.name),
            quoted(&prompt),
            quoted(judge.model),
        ),
    }
}

// judge argument paths become {{path}} template slots
fn mustache(prompt: &Value) -> String {
    match prompt {
        Value::Str(text) => text.clone(),
        Value::Template(template) => template
            .parts
            .iter()
            .map(|part| match part {
                Part::Lit(text) => text.clone(),
                Part::Dynamic(value) => format!("{{{{{}}}}}", slot_path(value)),
                Part::Ref(_) | Part::VarRef(_) => unreachable!("the modeler validated judge prompt holes"),
            })
            .collect(),
        _ => unreachable!("the modeler validated the judge prompt shape"),
    }
}

fn slot_path(value: &Value) -> String {
    match value {
        Value::ArgRef(arg) => arg_name(*arg).to_owned(),
        Value::Index { target, index, .. } => match &**index {
            Value::Str(key) => format!("{}.{key}", slot_path(target)),
            _ => unreachable!("the modeler validated judge prompt holes"),
        },
        _ => unreachable!("the modeler validated judge prompt holes"),
    }
}

fn quoted(value: &str) -> String {
    serde_json::to_string(value).expect("a string always encodes as JSON")
}
