use super::{CodeTarget, Error};
use crate::dsl::{Model, ScorerLang};
use crate::mocking::code::{
    self, Assembly, CodeGroup, CodebaseContext, CodebasePlan, Judge, Module, SourceFile, Target, languages::Languages,
    lowering, planning,
};
use crate::providers::braintrust::naming::slugify;
use std::{cell::RefCell, collections::BTreeMap};

pub(super) fn assemble(model: &Model, lang: ScorerLang, project: &str) -> Result<Vec<SourceFile>, Error> {
    let plans = planning::evals(model).map_err(Error::Agent)?;
    if model.experiments.is_empty() {
        return Ok(Vec::new());
    }
    let target = EvaluationTarget {
        target: CodeTarget::new(project),
        exports: RefCell::default(),
    };
    let scorers =
        code::assemble(&model.scorers, Some(lang), &Languages, &target).map_err(|error| Error::Agent(error.to_string()))?;
    let exports = target.exports.into_inner();
    let mut files = Vec::new();
    for plan in plans {
        let rows = lowering::cases(plan.dataset).map_err(Error::Agent)?;
        files.push(evaluation(&plan, &rows, lang, project, &exports));
    }
    files.extend(scorers.files.into_iter().map(|mut file| {
        file.name = format!("src/scorers/{}", file.name);
        file
    }));
    Ok(files)
}

struct Callable {
    file: String,
    function: String,
}

struct EvaluationTarget {
    target: CodeTarget,
    exports: RefCell<BTreeMap<String, Callable>>,
}
impl Target for EvaluationTarget {
    type Error = Error;
    fn slug(&self, name: &str) -> Option<String> {
        slugify(name)
    }
    fn code(&self, group: CodeGroup<'_>, module: Module) -> Result<Vec<SourceFile>, Error> {
        let file = planning::callable_name(group.stem, group.lang);
        for (item, function) in group.items.iter().zip(&module.functions) {
            self.exports.borrow_mut().insert(
                item.name.to_owned(),
                Callable {
                    file: file.clone(),
                    function: function.clone(),
                },
            );
        }
        self.target.code(group, module)
    }

    fn judge(&self, judge: Judge<'_>) -> Result<SourceFile, Error> {
        self.target.judge(judge)
    }
    fn codebase(&self, assembly: &Assembly, context: &CodebaseContext<'_>) -> Result<CodebasePlan, Error> {
        self.target.codebase(assembly, context)
    }
}

fn evaluation(
    plan: &planning::Evaluation<'_>,
    rows: &[serde_json::Value],
    lang: ScorerLang,
    project: &str,
    exports: &BTreeMap<String, Callable>,
) -> SourceFile {
    let experiment = plan.experiment;
    let stem = &plan.agent;
    let eval_stem = &plan.module;
    let mut functions = Vec::new();
    let mut imports = String::new();
    for scorer in &plan.scorers {
        let callable = exports.get(&scorer.name).expect("selected code scorers were assembled");
        let function = &callable.function;
        let file = &callable.file;
        imports.push_str(&match lang {
            ScorerLang::Python => format!("from scorers.{} import {function}\n", file.trim_end_matches(".py")),
            ScorerLang::Typescript => format!("import {{{function}}} from \"../scorers/{}\";\n", file),
        });
        functions.push(function.as_str());
    }
    let data = serde_json::to_string_pretty(&rows).unwrap();
    let project = serde_json::to_string(project).unwrap();
    let experiment_name = serde_json::to_string(&experiment.name).unwrap();
    let description = serde_json::to_string(&experiment.description).unwrap();
    let scores = functions.join(", ");
    let ts_description = experiment
        .description
        .as_ref()
        .map(|v| serde_json::to_string(v).unwrap())
        .unwrap_or_else(|| "undefined".into());
    let (name, contents) = match lang {
        ScorerLang::Python => (
            format!("src/evals/{eval_stem}_eval.py"),
            format!(
                "# generated by bts; edits will be overwritten.\nimport json\nfrom agents.{stem} import run_traced\n{imports}\n\nCASES = json.loads({data:?})\nSCORERS = [{scores}]\n\ndef task(input, hooks):\n    return run_traced(hooks.span, input)\n\ndef evaluate(project={project}, *, no_send_logs=False):\n    from braintrust import Eval\n    return Eval(project, experiment_name={experiment_name}, description=json.loads({description:?}), data=CASES, task=task, scores=SCORERS, no_send_logs=no_send_logs)\n\nif __name__ == \"__main__\":\n    print(evaluate().summary)\n"
            ),
        ),
        ScorerLang::Typescript => (
            format!("src/evals/{eval_stem}.eval.mts"),
            format!(
                "// generated by bts; edits will be overwritten.\nimport {{runTraced}} from \"../agents/{stem}.mts\";\n{imports}\n\nexport const cases = {data};\nexport const scorers = [{scores}];\nexport function task(input: unknown, hooks: {{span: Parameters<typeof runTraced>[0]}}): any {{\n    return runTraced(hooks.span, input);\n}}\nexport async function evaluate(project={project}, noSendLogs=false) {{\n    const {{Eval}} = await import(\"braintrust\");\n    return Eval(project, {{experimentName: {experiment_name}, description: {ts_description}, data: cases, task, scores: scorers}} , {{noSendLogs}});\n}}\n\nif (import.meta.main) console.log((await evaluate()).summary);\n"
            ),
        ),
    };
    SourceFile {
        name,
        contents,
        lang,
        slugs: Vec::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dsl::{Number, Value};
    use code::Item;

    #[test]
    fn callable_module_exports_the_emitters_declared_function() {
        let target = EvaluationTarget {
            target: CodeTarget::new("test"),
            exports: RefCell::default(),
        };
        let score = Value::Num(Number::Int(1));
        let items = [Item {
            name: "quality",
            slug: "quality",
            score: &score,
            steps: &[],
        }];
        let source = target
            .code(
                CodeGroup {
                    lang: ScorerLang::Typescript,
                    stem: "checks",
                    items: &items,
                },
                Module {
                    source: "function assess(output: unknown) { return 1; }\n".into(),
                    functions: vec!["assess".into()],
                },
            )
            .unwrap();
        assert!(source[0].contents.contains("export { assess };"));
        assert!(source[1].contents.contains("import {assess} from \"./checks.js\";"));
        assert!(!source[1].contents.contains("function assess"));
        let exports = target.exports.into_inner();
        assert_eq!(exports["quality"].function, "assess");
        assert_eq!(exports["quality"].file, "checks.ts");
    }
}
